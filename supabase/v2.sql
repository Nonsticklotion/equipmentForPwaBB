-- ---------- ประวัติซ่อมบำรุง ----------
create table if not exists public.maintenance_logs (
  id bigint generated by default as identity primary key,
  equipment_id bigint not null references public.equipment(id) on delete cascade,
  log_date date not null default current_date,
  kind text not null default 'PM'
    check (kind in ('PM','ตรวจวัด','ซ่อม','Overhaul','พันขดลวด','เปลี่ยนอะไหล่','อื่นๆ')),
  title text not null,
  detail text,
  ir_mohm numeric,         -- Insulation Resistance (MΩ)
  current_a numeric,       -- กระแสขณะทำงาน (A)
  vibration numeric,       -- mm/s
  temp_c numeric,          -- อุณหภูมิ (°C)
  performed_by text,       -- ผู้ปฏิบัติงาน / ผู้รับจ้าง
  cost numeric,            -- ค่าใช้จ่าย (บาท)
  created_by uuid default auth.uid(),
  created_at timestamptz default now()
);
create index if not exists maintenance_logs_eq_idx on public.maintenance_logs(equipment_id, log_date desc);

alter table public.maintenance_logs enable row level security;
drop policy if exists "read all" on public.maintenance_logs;
create policy "read all" on public.maintenance_logs for select using (true);
drop policy if exists "admin write" on public.maintenance_logs;
create policy "admin write" on public.maintenance_logs for all
  using (public.is_admin()) with check (public.is_admin());

-- ---------- ให้กู้คืน backup พร้อม id เดิมได้ ----------
alter table public.stations         alter column id set generated by default;
alter table public.buildings        alter column id set generated by default;
alter table public.categories       alter column id set generated by default;
alter table public.equipment        alter column id set generated by default;
alter table public.equipment_photos alter column id set generated by default;

-- หลังกู้คืน: ตั้งเลข id ถัดไปให้ต่อจากค่าสูงสุด (เรียกจากหน้าเว็บ, แอดมินเท่านั้น)
create or replace function public.reset_sequences()
returns void language plpgsql security definer set search_path = public as $$
declare t text;
begin
  if not public.is_admin() then raise exception 'admin only'; end if;
  foreach t in array array['stations','buildings','categories','equipment','equipment_photos','maintenance_logs'] loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from public.%I), 0) + 1, false)',
      'public.' || t, t);
  end loop;
end; $$;
revoke all on function public.reset_sequences() from public, anon;
grant execute on function public.reset_sequences() to authenticated;
